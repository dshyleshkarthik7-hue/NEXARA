#!/usr/bin/env bash
# Inspect a live Firecracker process and verify kernel-enforced jail controls.
set -Eeuo pipefail
fail() { echo "JAIL VERIFICATION FAILED: $*" >&2; exit 1; }
[[ "$(uname -s)" == Linux ]] || fail "Linux is required"
[[ "$(id -u)" == 0 ]] || fail "run as root so /proc and cgroup state are readable"
pid="${1:-}"
[[ "$pid" =~ ^[1-9][0-9]*$ && -d "/proc/$pid" ]] || fail "usage: sudo $0 FIRECRACKER_PID"
proc="/proc/$pid"
exe="$(readlink "$proc/exe")"
[[ "$(basename "$exe")" == firecracker ]] || fail "PID does not execute Firecracker: $exe"
status="$(cat "$proc/status")"
field() { awk -v key="$1" '$1 == key ":" { print $2; exit }' <<<"$status"; }
uid="$(field Uid)"
read -r real_uid effective_uid _ <<<"$uid"
[[ -n "$effective_uid" && "$effective_uid" -ne 0 ]] || fail "Firecracker effective UID is root"
[[ "$(field NoNewPrivs)" == 1 ]] || fail "NoNewPrivs is not enabled"
[[ "$(field Seccomp)" == 2 ]] || fail "process is not running in seccomp filter mode"
nspid="$(awk '$1 == "NSpid:" { print NF-1 }' <<<"$status")"
[[ "${nspid:-0}" -ge 2 ]] || fail "process is not in a distinct PID namespace"
host_net="$(readlink /proc/1/ns/net)"
guest_net="$(readlink "$proc/ns/net")"
[[ "$host_net" != "$guest_net" ]] || fail "process shares the host network namespace"
cgroup_line="$(awk -F: '$1 == "0" { print $3 }' "$proc/cgroup")"
[[ -n "$cgroup_line" && "$cgroup_line" == *"${NEXARA_CGROUP_PREFIX:-nexara}"* ]] || fail "process is not in the expected NEXARA cgroup: $cgroup_line"
cg="/sys/fs/cgroup$cgroup_line"
[[ -f "$cg/cpu.max" && -f "$cg/memory.max" && -f "$cg/pids.max" ]] || fail "required cgroup v2 controller files are missing"
read -r cpu_quota cpu_period < "$cg/cpu.max"
[[ "$cpu_quota" =~ ^[0-9]+$ && "$cpu_period" =~ ^[0-9]+$ && "$cpu_period" -gt 0 ]] || fail "CPU quota is unlimited or malformed"
memory_max="$(cat "$cg/memory.max")"
pids_max="$(cat "$cg/pids.max")"
[[ "$memory_max" =~ ^[0-9]+$ ]] || fail "memory limit is unlimited or malformed"
[[ "$pids_max" =~ ^[0-9]+$ ]] || fail "PID limit is unlimited or malformed"
echo "PASS: executable=$exe pid=$pid uid=$effective_uid"
echo "PASS: NoNewPrivs=1 Seccomp=2 PID namespace isolated network namespace isolated"
echo "PASS: cgroup=$cgroup_line cpu.max=$cpu_quota $cpu_period memory.max=$memory_max pids.max=$pids_max"
